def _ma(vals, n):
    if not vals or len(vals) < n:
        return None
    seg = vals[-n:]
    if any(v is None for v in seg):
        return None
    return sum(seg) / n


def _median(xs):
    if not xs:
        return 0.0
    s = sorted(xs)
    return s[len(s) // 2]


def _has(name):
    return globals().get(name) is not None


