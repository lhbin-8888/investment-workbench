def main():
    kl = json.load(open(os.path.join(ROOT, "ths_kline.json"), encoding="utf-8"))
    flow = json.load(open(os.path.join(ROOT, "raw_flow_ind.json"), encoding="utf-8"))
    em = {}
    for x in flow:
        em[x["BOARD_CODE"]] = x["BOARD_NAME"]

    # 同花顺名索引（优先行业板块，其次概念）
    byname = {}
    for code, v in kl.items():
        byname.setdefault(norm(v["name"]), []).append(
            {"code": code, "name": v["name"], "type": v["type"]})

    out, miss = {}, []
    for code, name in em.items():
        hit, how = None, ""
        n = norm(name)
        # 1 精确
        if n in byname:
            cand = byname[n]
            hit = next((c for c in cand if c["type"] == "industry"), cand[0])
            how = "exact"
        # 2 人工别名
        if not hit and name in MANUAL:
            tgt = MANUAL[name]
            if norm(tgt) in byname:
                cand = byname[norm(tgt)]
                hit = next((c for c in cand if c["type"] == "industry"), cand[0])
                how = "manual"
        # 3 模糊
        if not hit:
            cands = difflib.get_close_matches(n, list(byname.keys()), n=1, cutoff=0.82)
            if cands:
                cand = byname[cands[0]]
                hit = next((c for c in cand if c["type"] == "industry"), cand[0])
                how = "fuzzy:" + cands[0]
        if hit:
            out[code] = {"em_name": name, "ths_code": hit["code"],
                          "ths_name": hit["name"], "how": how}
        else:
            miss.append(name)

    json.dump(out, open(os.path.join(ROOT, "em_to_ths.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"映射 {len(out)}/{len(em)}")
    if miss:
        print(f"未映射 {len(miss)}:", miss)


if __name__ == "__main__":
    main()
