def main():
    kl = json.load(open(os.path.join(ROOT, "ths_kline.json"), encoding="utf-8"))
    byname = {}
    for code, v in kl.items():
        byname.setdefault(norm(v["name"]), []).append(
            {"code": code, "name": v["name"], "type": v["type"]})

    src = json.load(open(os.path.join(ROOT, "actual_reports.json"), encoding="utf-8"))
    allnames = set(r["n"] for v in src.values() for r in v["records"] if r.get("n"))
    # 东财板块名也纳入（作为跨源桥梁）
    flow = json.load(open(os.path.join(ROOT, "raw_flow_ind.json"), encoding="utf-8"))
    allnames |= set(x["BOARD_NAME"] for x in flow)

    out, miss = {}, []
    for name in sorted(allnames):
        nn = norm(name)
        hit, how = None, ""
        if nn in byname:
            cand = byname[nn]
            hit = next((c for c in cand if c["type"] == "industry"), cand[0])
            how = "exact"
        if not hit:
            # 先查去尾缀名，再查原名
            for key in (name, name.replace("Ⅱ", "").replace("Ⅲ", "")):
                if key in MANUAL:
                    tgt = MANUAL[key]
                    if norm(tgt) in byname:
                        cand = byname[norm(tgt)]
                        hit = next((c for c in cand if c["type"] == "industry"), cand[0])
                        how = "manual:" + key
                        break
        if not hit:
            cand = difflib.get_close_matches(nn, list(byname.keys()), n=1, cutoff=0.82)
            if cand:
                c2 = byname[cand[0]]
                hit = next((c for c in c2 if c["type"] == "industry"), c2[0])
                how = "fuzzy:" + cand[0]
        if hit:
            out[name] = hit
        else:
            miss.append(name)

    json.dump(out, open(os.path.join(ROOT, "name_map.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"映射 {len(out)}/{len(allnames)}，未匹配 {len(miss)}")
    if miss:
        print("未匹配:", miss)


if __name__ == "__main__":
    main()
